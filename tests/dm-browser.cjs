const {chromium,webkit}=require('playwright');
const assert=require('node:assert/strict');
const {mkdirSync}=require('node:fs');
mkdirSync('test-results',{recursive:true});
(async()=>{
 for(const [engine,size] of [[chromium,{width:390,height:844}],[webkit,{width:820,height:1180}]]){
  const browser=await engine.launch({headless:true});
  const context=await browser.newContext({viewport:size,serviceWorkers:'block'});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>route.request().url().startsWith('http://localhost:4173')?route.continue():route.abort());
  await page.goto('http://localhost:4173');
  await page.locator('.pr-import summary').click();
  await page.locator('#homeDmReel').fill('https://www.instagram.com/reel/ABCde1234/');
  await page.locator('#homeDmBrand').fill('@lucidclub');
  await page.locator('#homeDmQuickForm button').click();
  await page.locator('#dmEditor[open]').waitFor();
  assert.equal(await page.locator('#dmEditorPreview iframe').count(),1);
  await page.locator('#dmEditorText').fill('Hey! My edited draft.');
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw new Error('denied')}}}));
  await page.locator('#dmEditorCopy').click();
  await page.getByText('Bitte den markierten Text manuell kopieren, dann den Chat öffnen.',{exact:true}).waitFor();
  assert.equal(await page.locator('#dmEditorChat').getAttribute('href'),'https://ig.me/m/lucidclub');
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.copied=text;}}}));
  await page.locator('#dmEditorCopy').click();
  assert.equal(await page.evaluate(()=>window.copied),'Hey! My edited draft.\n\nhttps://www.instagram.com/reel/ABCde1234/');
  await page.locator('#dmEditorClose').click();
  await page.locator('#dmEditorPreview iframe').waitFor({state:'detached'});
  assert.equal(await page.locator('#dmEditorPreview iframe').count(),0);
  await page.reload();
  await page.locator('.pr-video-card').first().waitFor();
  await page.screenshot({path:'test-results/home-feed-'+engine.name()+'.png'});
  await page.locator('.home-dm-all').click();
  await page.locator('[data-action="dm-edit"]').click();
  assert.equal(await page.locator('#dmEditorText').inputValue(),'Hey! My edited draft.');
  assert.equal(await page.locator('#dmEditor').evaluate(e=>e.scrollWidth<=e.clientWidth+1),true);
  await page.screenshot({path:'test-results/dm-editor-'+engine.name()+'-'+size.width+'.png',fullPage:false});
  await page.locator('#dmEditorClose').click();
  page.once('dialog',d=>d.dismiss());
  await page.locator('[data-action="dm-sent"]').click();
  assert.equal(await page.locator('#dmPreparedCount').innerText(),'1');
  page.once('dialog',d=>d.accept());
  await page.locator('[data-action="dm-sent"]').click();
  await page.locator('#dmDraftFilter').selectOption('prepared');
  assert.equal(await page.locator('#dmDraftList .dm-card').count(),0);
  await page.locator('#dmDraftFilter').selectOption('sent');
  assert.equal(await page.locator('#dmDraftList .dm-card').count(),1);
  page.once('dialog',d=>d.accept());
  await page.locator('[data-action="dm-replied"]').click();
  assert.equal(await page.locator('#dmDraftList .dm-card').count(),0);
  await page.locator('#dmDraftFilter').selectOption('replied');
  assert.equal(await page.locator('[data-action="offer-from-dm"]').count(),1);
  assert.equal(await page.locator('#dmSentCount').innerText(),'0');
  // Test navigation is intercepted: no message or action reaches Instagram.
  await page.goto('http://localhost:4173');
  await page.locator('.pr-import summary').click();
  await page.locator('#homeDmReel').fill('https://www.instagram.com/reel/ABCde1234/');
  await page.locator('#homeDmBrand').fill('returnbrand');
  await page.locator('#homeDmQuickForm button').click();
  await page.locator('#dmEditorText').fill('Copied handoff message');
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw Error('denied')}}}));
  await page.locator('#dmEditorVideoTap').click();
  await page.getByText('Kopieren blockiert. Text manuell kopieren und das Original unten öffnen.',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('pr-hunter-state-v1')).dmDrafts.some(d=>d.pendingMessage)),false);
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{}}}));
  await page.route('https://www.instagram.com/reel/ABCde1234/',route=>route.request().frame()===page.mainFrame()?route.fulfill({contentType:'text/html',body:'Test-only external destination'}):route.abort());
  await page.locator('#dmEditorVideoTap').click();
  await page.waitForURL('https://www.instagram.com/reel/ABCde1234/');
  await page.goto('http://localhost:4173');
  await page.locator('#dmReturnDialog[open]').waitFor();
  assert.equal(await page.locator('#dmReturnText').inputValue(),'Copied handoff message\n\nhttps://www.instagram.com/reel/ABCde1234/');
  await page.locator('#dmReturnNo').click();
  assert.equal(await page.locator('#dmTotalSentCount').innerText(),'1');
  await page.locator('.home-dm-all').click();
  await page.locator('#dmDraftFilter').selectOption('prepared');
  await page.locator('[data-action="dm-edit"]').click();
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{}}}));
  await page.locator('#dmEditorVideoTap').click();
  await page.waitForURL('https://www.instagram.com/reel/ABCde1234/');
  await page.goto('http://localhost:4173');
  await page.locator('#dmReturnDialog[open]').waitFor();
  await page.locator('#dmReturnText').fill('Actually sent, edited in Instagram');
  await page.screenshot({path:'test-results/return-confirmation-'+engine.name()+'.png'});
  await page.locator('#dmReturnYes').click();
  assert.equal(await page.locator('#dmTotalSentCount').innerText(),'2');
  const card=page.locator('.dm-card').filter({has:page.locator('h3',{hasText:'@returnbrand'})});
  await card.locator('.dm-sent-record summary').click();
  await card.locator('[data-dm-shipping]').fill('6.99');
  await card.locator('[data-dm-shipping]').press('Tab');
  await page.reload();
  assert.equal(await page.locator('#dmReturnDialog').evaluate(d=>d.open),false);
  const persisted=await page.evaluate(()=>JSON.parse(localStorage.getItem('pr-hunter-state-v1')).dmDrafts.find(d=>d.brand==='returnbrand'));
  assert.equal(persisted.sentMessage,'Actually sent, edited in Instagram');
  assert.equal(persisted.shippingEUR,6.99);
  assert.equal(persisted.status,'sent');
  // Phase 20: genuine self-reported reply only, local preferences and Smart Inbox.
  await page.locator('.alert-trigger[data-tab="alerts"]').click();
  await page.locator('#alertList .alert-entry').filter({hasText:'Antwort von @lucidclub selbst bestätigt'}).waitFor();
  assert.equal(await page.locator('#alertReelsPref').isChecked(),true);
  assert.equal(await page.locator('#alertAutoRefreshPref').isChecked(),true);
  await page.locator('#alertAutoRefreshPref').uncheck();
  await page.locator('#alertReelsPref').uncheck();
  await page.screenshot({path:'test-results/phase20-smart-inbox-'+engine.name()+'.png',fullPage:false});
  await page.reload();
  await page.locator('.alert-trigger[data-tab="alerts"]').click();
  assert.equal(await page.locator('#alertAutoRefreshPref').isChecked(),false);
  assert.equal(await page.locator('#alertReelsPref').isChecked(),false);
  await page.locator('#markAllAlertsRead').click();
  assert.equal(await page.locator('#alertCount').isVisible(),false);
  await page.locator('#clearReadAlerts').click();
  assert.equal(await page.locator('#alertList').getByText('Antwort von @lucidclub selbst bestätigt').count(),0);
  assert.ok((await page.evaluate(()=>JSON.parse(localStorage.getItem('pr-hunter-state-v1')).phase20.seenNoticeIds)).some(id=>id.startsWith('reply:')));
  console.log(engine.name(),'Phase 20 Smart Inbox / manual replies / preferences / persistence passed');
  console.log(engine.name(),'Phase 18 handoff / No / Yes / snapshot / shipping / reload passed');
  assert.deepEqual(errors,[]);
  console.log(engine.name(),size.width,'passed: editing, persistence, preview cleanup, clipboard success/denial, manual status confirmations and filters');
  await browser.close();
 }
})().catch(e=>{console.error(e);process.exit(1)});
